import fs from 'node:fs';
import path from 'node:path';
import readline from 'node:readline/promises';
import { stdin as input, stdout as output } from 'node:process';

const root = process.cwd();
const target = path.join(root, '.env.local');
const rl = readline.createInterface({ input, output });
const lineIterator = rl[Symbol.asyncIterator]();
const clean = (value) => value.trim().replace(/^['"]|['"]$/g, '').replace(/\/$/, '');

async function ask(question) {
  output.write(question);
  const next = await lineIterator.next();
  if (next.done) throw new Error('ورودی ناقص است؛ دستور را دوباره در ترمینال اجرا کن.');
  return next.value;
}

function isSecretKey(key) {
  if (/sb_secret_|service_role/i.test(key)) return true;
  const payload = key.split('.')[1];
  if (!payload) return false;
  try {
    return JSON.parse(Buffer.from(payload, 'base64url').toString('utf8')).role === 'service_role';
  } catch {
    return false;
  }
}

try {
  console.log('\nNOWERA · راه‌اندازی اتصال Supabase\n');
  console.log('از Supabase → Project Settings → API، آدرس پروژه و کلید Publishable/anon را بردار.');
  console.log('کلید service_role یا secret را وارد نکن؛ این کلید برای اتصال مرورگر نیست.\n');

  const url = clean(await ask('Project URL (مثل https://xxxx.supabase.co): '));
  if (!/^https:\/\/[a-zA-Z0-9.-]+\.supabase\.co$/.test(url)) {
    throw new Error('آدرس پروژه معتبر نیست. باید شبیه https://xxxx.supabase.co باشد.');
  }

  const key = clean(await ask('Publishable key یا anon key: '));
  if (!key || isSecretKey(key)) {
    throw new Error('کلید خالی یا secret/service_role است. کلید Publishable/anon را وارد کن.');
  }

  const content = [
    '# Generated by npm run setup. This file is ignored by Git.',
    `VITE_SUPABASE_URL=${url}`,
    `VITE_SUPABASE_PUBLISHABLE_KEY=${key}`,
    '',
  ].join('\n');

  if (fs.existsSync(target)) {
    const answer = (await ask('.env.local از قبل وجود دارد. جایگزین شود؟ (y/N): ')).trim().toLowerCase();
    if (answer !== 'y' && answer !== 'yes') {
      console.log('فایل قبلی حفظ شد.');
    } else {
      fs.writeFileSync(target, content, { mode: 0o600 });
      console.log('\nاتصال ذخیره شد. حالا اجرا کن: npm run diagnose سپس npm run dev\n');
    }
  } else {
    fs.writeFileSync(target, content, { mode: 0o600 });
    console.log('\nاتصال ذخیره شد. حالا اجرا کن: npm run diagnose سپس npm run dev\n');
  }
} catch (error) {
  console.error(`\nراه‌اندازی انجام نشد: ${error.message}\n`);
  process.exitCode = 1;
} finally {
  rl.close();
}
